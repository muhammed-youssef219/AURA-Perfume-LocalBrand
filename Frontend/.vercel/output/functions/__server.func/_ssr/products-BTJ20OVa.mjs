var PRODUCTS_STORAGE_KEY = "aura_custom_products";
function getStoredProducts() {
	if (typeof window === "undefined") return defaultProducts;
	try {
		const raw = localStorage.getItem(PRODUCTS_STORAGE_KEY);
		if (!raw) return defaultProducts;
		const parsed = JSON.parse(raw);
		if (Array.isArray(parsed) && parsed.length > 0) return parsed;
	} catch {}
	return defaultProducts;
}
function saveStoredProducts(list) {
	if (typeof window === "undefined") return;
	localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(list));
	window.dispatchEvent(new Event("aura_products_updated"));
}
function addStoredProduct(product) {
	saveStoredProducts([product, ...getStoredProducts()]);
}
function updateStoredProduct(product) {
	saveStoredProducts(getStoredProducts().map((p) => p.id === product.id ? product : p));
}
function deleteStoredProduct(id) {
	saveStoredProducts(getStoredProducts().filter((p) => p.id !== id));
}
function resetStoredProducts() {
	if (typeof window === "undefined") return;
	localStorage.removeItem(PRODUCTS_STORAGE_KEY);
	window.dispatchEvent(new Event("aura_products_updated"));
}
function useProducts() {
	const [items, setItems] = import_react.useState(getStoredProducts());
	import_react.useEffect(() => {
		const sync = () => {
			setItems(getStoredProducts());
		};
		sync();
		window.addEventListener("aura_products_updated", sync);
		window.addEventListener("storage", sync);
		return () => {
			window.removeEventListener("aura_products_updated", sync);
			window.removeEventListener("storage", sync);
		};
	}, []);
	return items;
}
var getProduct = (id) => {
	return getStoredProducts().find((p) => p.id === id) || defaultProducts.find((p) => p.id === id);
};
var AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";
var toArabicDigits = (value) => String(value).replace(/[0-9]/g, (d) => AR_DIGITS[Number(d)]);
var formatPrice = (v) => {
	return `${toArabicDigits(Math.round(v).toLocaleString("en-US").replace(/,/g, "٬"))} \u062C.\u0645`;
};
